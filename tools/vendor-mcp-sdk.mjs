#!/usr/bin/env node
// Bundles the MCP SDK server parts into lib/vendor/mcp-sdk.mjs: the plugin runs without node_modules, so it cannot import the package.
import { build } from "esbuild";
import { readFileSync } from "node:fs";

const ENTRY = `export { Server } from "@modelcontextprotocol/sdk/server/index.js";
export { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
export { CallToolRequestSchema, ListToolsRequestSchema } from "@modelcontextprotocol/sdk/types.js";
`;
const OUT = new URL("../lib/vendor/mcp-sdk.mjs", import.meta.url).pathname;
const VERSION = JSON.parse(readFileSync(new URL("../node_modules/@modelcontextprotocol/sdk/package.json", import.meta.url), "utf8")).version;

await build({
  stdin: { contents: ENTRY, resolveDir: new URL("..", import.meta.url).pathname, loader: "js" },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  outfile: OUT,
  legalComments: "eof",
  banner: { js: `// Generated by tools/vendor-mcp-sdk.mjs from @modelcontextprotocol/sdk ${VERSION}; do not edit. Run npm run vendor:mcp to regenerate.` },
  logLevel: "warning",
});
console.log(`wrote ${OUT} (sdk ${VERSION})`);
